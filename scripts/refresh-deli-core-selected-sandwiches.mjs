import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import XLSX from "xlsx";
import * as pdfjs from "pdfjs-dist/legacy/build/pdf.mjs";

const root = resolve(import.meta.dirname, "..");
const menuItemsPath = resolve(root, "src/data/menuItems.json");
const catalogPath = resolve(root, "src/features/commissary-ordering/deliCoreCatalog.js");
const targetMenu = "AMZ: Deli Core";
const sourceVersion = "deli-core-selected-refresh-2026-10-29";

