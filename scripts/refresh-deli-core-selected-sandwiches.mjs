const unsupported = Object.freeze([
  { mrn: "234913", name: "Shrimp Avocado Corn Wrap", reason: "No exact-MRN recipe or cost row was present in the supplied sources." },
  { mrn: "141826.1", name: "Mediterranean Tuna Salad Sandwich", reason: "The recipe pack contains MRN 141826, not 141826.1, and the cost workbook contains neither MRN." },
]);

function argValue(name) {
  const prefix = `${name}=`;
  return process.argv.find((arg) => arg.startsWith(prefix))?.slice(prefix.length) || "";
}

function text(value) {
  return String(value ?? "").normalize("NFKC").replace(/^'/, "").trim();
}

function number(value) {
  if (value === null || value === undefined || value === "") return null;
  const parsed = Number(String(value).replace(/[$,%\s,]/g, ""));
  return Number.isFinite(parsed) ? parsed : null;
}

function percentage(value) {
  const parsed = number(value);
  if (parsed === null) return null;
  return parsed > 1 ? parsed / 100 : parsed;
}

function round(value, places = 6) {
  return Number(Number(value).toFixed(places));
}

function sha256(path) {
  return createHash("sha256").update(readFileSync(path)).digest("hex").toUpperCase();
}

function reportRows(path) {
  const workbook = XLSX.readFile(path, { raw: true, cellFormula: true });
  const sheet = workbook.Sheets.Report;
  if (!sheet) throw new Error("The cost workbook needs a Report sheet.");
  const formulas = Object.entries(sheet).filter(([key, cell]) => !key.startsWith("!") && cell?.f);
  if (formulas.length) throw new Error(`The cost workbook contains ${formulas.length} formula cells; provide a value-only export.`);
  return XLSX.utils.sheet_to_json(sheet, { defval: "", raw: true });
}

async function recipePageEvidence(path) {
  const data = new Uint8Array(readFileSync(path));
  const document = await pdfjs.getDocument({ data, disableWorker: true }).promise;
  if (document.numPages !== 107) throw new Error(`Expected the 107-page recipe pack, found ${document.numPages} pages.`);
  const evidence = new Map();
  const completeText = [];
  for (let pageNumber = 1; pageNumber <= document.numPages; pageNumber += 1) {
    const page = await document.getPage(pageNumber);
    const content = await page.getTextContent();
    const pageText = content.items.map((item) => item.str).join(" ").replace(/\s+/g, " ").trim();
    completeText.push(pageText);
    for (const [mrn, expectedPage] of targetRecipePages) {
      if (pageNumber === expectedPage && pageText.includes(`(${mrn})`)) {
        evidence.set(mrn, { page: pageNumber, pageText });
      }
    }
  }
  for (const [mrn, page] of targetRecipePages) {
    if (!evidence.has(mrn)) throw new Error(`Recipe MRN ${mrn} was not found on expected PDF page ${page}.`);
  }
  const joined = completeText.join("\n");
  if (joined.includes("(234913)")) throw new Error("MRN 234913 unexpectedly appeared; review the explicit omission before importing.");
  if (joined.includes("(141826.1)")) throw new Error("MRN 141826.1 unexpectedly appeared; review the exact-MRN omission before importing.");
  if (!joined.includes("(141826)")) throw new Error("Expected the non-matching MRN 141826 evidence for the documented tuna omission.");
  return evidence;
}

function renderCatalog({ items, costHash, recipeHash }) {
  const payload = {
    version: 1,
    menu: targetMenu,
    itemSource: "supabase.recipe_items",
    recipeDocumentSource: "supabase.recipe_item_documents",
    exactMrnRequired: true,
    source: {
      costWorkbook: "Deli Core Item Cost.xlsx",
      costWorkbookSha256: costHash,
      recipePack: "Deli Core Recipe PAck.pdf",
      recipePackSha256: recipeHash,
      verifiedAt: "2026-10-29",
    },
    items: items.map((item) => ({
      mrn: item.mrn,
      name: item.item,
      station: item.station,
      recipePage: targetRecipePages.get(item.mrn),
    })),
    unsupported,
  };
  return `// Generated by scripts/refresh-deli-core-selected-sandwiches.mjs from Alex's reviewed 2026-10-29 Deli sources.\n// Costs remain authoritative in Supabase recipe_items; recipe files remain private Supabase documents.\n\nexport const DELI_CORE_SELECTED_CATALOG = Object.freeze(${JSON.stringify(payload, null, 2)});\n\nexport const DELI_CORE_SELECTED_MRNS = Object.freeze(DELI_CORE_SELECTED_CATALOG.items.map(({ mrn }) => mrn));\n`;
}

async function main() {
  const costSource = resolve(argValue("--cost-source"));
  const recipeSource = resolve(argValue("--recipe-source"));
  if (!costSource || !recipeSource) {
    throw new Error("Pass --cost-source=<xlsx> and --recipe-source=<pdf>.");
  }

  const costHash = sha256(costSource);
  const recipeHash = sha256(recipeSource);
  const rows = reportRows(costSource);
  const costsByMrn = new Map(rows.map((row) => [text(row.MRN), row]).filter(([mrn]) => mrn));
  const evidence = await recipePageEvidence(recipeSource);
  const menuItems = JSON.parse(readFileSync(menuItemsPath, "utf8").replace(/^\uFEFF/, ""));
  const deliRows = menuItems.filter((row) => row.menu === targetMenu);
  if (deliRows.length !== 41) throw new Error(`Expected 41 existing ${targetMenu} rows, found ${deliRows.length}.`);
  const deliByMrn = new Map(deliRows.map((row) => [text(row.mrn), row]));

  const refreshed = [];
  for (const [mrn, recipePage] of targetRecipePages) {
    const cost = costsByMrn.get(mrn);
    const current = deliByMrn.get(mrn);
    if (!cost) throw new Error(`The cost workbook is missing exact MRN ${mrn}.`);
    if (!current) throw new Error(`The existing shared Deli Core menu is missing exact MRN ${mrn}.`);
    if (text(cost["Menu Name"]) !== targetMenu) throw new Error(`MRN ${mrn} is not scoped to ${targetMenu}.`);
    const itemCost = number(cost["Item Cost"]);
    const wastePct = percentage(cost["Waste %"]);
    const trueCost = number(cost["Item + Waste Cost"]);
    const price = number(cost["Sell Price"]);
    if (!(itemCost > 0) || !(wastePct >= 0) || !(trueCost > 0) || !(price > 0)) throw new Error(`MRN ${mrn} has incomplete cost or sell-price data.`);
    if (Math.abs(round(itemCost * (1 + wastePct)) - round(trueCost)) > 0.00001) throw new Error(`MRN ${mrn} Item + Waste Cost does not reconcile.`);
    if (!evidence.has(mrn)) throw new Error(`MRN ${mrn} has no validated recipe evidence.`);

    current.portion = text(cost.Portion) || current.portion;
    current.price = price;
    current.itemCost = itemCost;
    current.wastePct = wastePct;
    current.trueCost = trueCost;
    current.dataSource = "menuworks-deli-core-reviewed-refresh";
    current.sourceDataVersion = sourceVersion;
    current.sourceFileName = "Deli Core Item Cost.xlsx + Deli Core Recipe PAck.pdf";
    current.costSourceSha256 = costHash;
    current.recipeSourceSha256 = recipeHash;
    current.recipeEvidence = {
      fileName: "Deli Core Recipe PAck.pdf",
      page: recipePage,
      exactMrn: true,
      documentType: "recipe-file",
    };
    current.menuWorksRaw = {
      ...(current.menuWorksRaw || {}),
      "Menu Name": targetMenu,
      Station: text(cost.Station) || current.station,
      "Recipe Number": mrn,
      "Menu Item": text(cost["Menu Item"]),
      Portion: current.portion,
      "Sell Price": price,
      "Item Cost": itemCost,
      "Waste %": wastePct,
      "Item + Waste Cost": trueCost,
    };
    refreshed.push(current);
  }

  for (const omission of unsupported) {
    if (costsByMrn.has(omission.mrn)) throw new Error(`Documented unsupported MRN ${omission.mrn} unexpectedly has a cost row.`);
  }

  const catalog = renderCatalog({ items: refreshed, costHash, recipeHash });
  if (process.argv.includes("--check")) {
    if (readFileSync(catalogPath, "utf8").replace(/\r\n/g, "\n") !== catalog) throw new Error("Deli selected catalog is stale.");
  } else {
    writeFileSync(menuItemsPath, `${JSON.stringify(menuItems, null, 2)}\n`);
    writeFileSync(catalogPath, catalog);
  }

  console.log(JSON.stringify({
    menu: targetMenu,
    refreshedRows: refreshed.length,
    preservedMenuRows: deliRows.length - refreshed.length,
    unsupported,
    sourceVersion,
    costHash,
    recipeHash,
  }, null, 2));
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
