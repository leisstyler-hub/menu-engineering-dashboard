import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
const path = '../src/features/menu-engineering/weighPayModel.js';
assert.ok(existsSync(new URL(path, import.meta.url)), 'W&P qualification model must exist');
const { evaluateItem, evaluateMenus, portionWeightOz, WP_PRICE_PER_LB, itemIdentity } = await import(path);
const item = (extra = {}) => ({ menu: 'Kitchen', item: 'Roast Chicken', mrn: '000001.123456789', trueCost: 1, portionOz: 8, category: 'Entree', ...extra });
assert.equal(WP_PRICE_PER_LB, 11.20);
assert.equal(evaluateItem(item()).status, 'Allowed');
assert.equal(evaluateItem(item({ trueCost: WP_PRICE_PER_LB * .4, portionOz: 16 })).status, 'Allowed');
assert.equal(evaluateItem(item({ trueCost: WP_PRICE_PER_LB * .40001, portionOz: 16 })).status, 'Blocked');
for (const trueCost of [null, '', 'bad', -1, Infinity]) assert.equal(evaluateItem(item({ trueCost })).status, 'Needs cost');
assert.equal(evaluateItem(item({ trueCost: 0 })).status, 'Allowed');
assert.equal(evaluateItem(item({ portionOz: null, portion: '1 piece' })).status, 'Needs weight');
assert.equal(portionWeightOz(item({ portionOz: null, portion: '0.5 lb' })), 8);
assert.equal(portionWeightOz(item({ portionOz: null, portion: '100 g' })), 100 / 28.349523125);
assert.equal(portionWeightOz(item({ portionOz: null, portion: '12 fl oz' })), null);
assert.equal(portionWeightOz(item({ portionOz: null, portion: '1 cup' })), null);
assert.equal(evaluateItem(item({ item: 'Salmon' })).status, 'Allowed');
assert.equal(evaluateItem(item({ item: 'Cauliflower Steak' })).status, 'Allowed');
assert.equal(evaluateItem(item({ item: 'Grain Flank Tacos (Lentil and Seitan "Steak")' })).reasons.includes('Steak / whole-muscle beef exclusion'), false);
assert.equal(evaluateItem(item({ item: 'Plant Based Beef Kofta', veganTag: 'Vegan' })).status, 'Allowed');
assert.equal(evaluateItem(item({ item: 'Ground Beef' })).status, 'Allowed');
assert.equal(evaluateItem(item({ item: 'Lamb Kebab' })).status, 'Blocked');
assert.equal(evaluateItem(item({ item: 'Pork Tenderloin' })).status, 'Blocked');
assert.equal(evaluateItem(item({ item: 'Chicken Sandwich' })).status, 'Blocked');
assert.equal(evaluateItem(item({ category: 'Extension' })).status, 'Blocked');
assert.equal(evaluateItem(item({ item: 'Chicken Bowl', menu: 'Bibimbowl' })).status, 'Review');
const rows = [item(), item({ mrn: '2', item: 'Rice' }), item({ mrn: '3', item: 'Carrots' }), item({ mrn: '4', item: 'Salmon', trueCost:3 }), item({ mrn: '5', item: 'Missing', trueCost: null }), item()];
const menu = evaluateMenus(rows)[0];
assert.equal(menu.total, 5); assert.equal(menu.allowed, 3); assert.equal(menu.passRate, .6); assert.equal(menu.status, 'Pass');
assert.equal(evaluateMenus([]).length, 0);
assert.equal(evaluateMenus([item({ trueCost: null })])[0].status, 'Conditional');
assert.equal(evaluateMenus([item({ item: 'Salmon' })])[0].status, 'Pass');
assert.equal(evaluateMenus(rows, {}, { trusted: false })[0].status, 'Conditional');
const salmon = rows[3];
const overrides = { [itemIdentity(salmon)]: { decision: 'allow', reason: 'Validated exception' } };
const changed = evaluateMenus(rows, overrides)[0];
assert.equal(changed.allowed, 4); assert.equal(changed.calculatedAllowed, 3); assert.equal(changed.status, 'Conditional');
assert.equal(evaluateItem(salmon, { decision: 'allow', reason: '' }).status, 'Blocked');
assert.equal(evaluateItem(item({ trueCost: null }), { decision: 'allow', reason: 'Test' }).status, 'Needs cost');
assert.notEqual(itemIdentity(item({ portionOz: 4 })), itemIdentity(item({ portionOz: 8 })));
assert.equal(evaluateItem(item({ mrn: '000001.123456789' })).mrn, '000001.123456789');
assert.equal(evaluateItem(item({ item: 'Lamb Mushroom Kofta' })).status, 'Blocked');
assert.equal(evaluateItem(item({ item: 'Beef Steak with Cauliflower' })).status, 'Allowed');
assert.equal(evaluateMenus([item(), item({item:'Alias for the same recipe'})])[0].total, 1);
console.log('W&P qualification: price, exact thresholds, missing inputs, mass units, exclusions, unique identities, session overrides and source trust passed.');
