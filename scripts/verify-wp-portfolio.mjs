import assert from 'node:assert/strict';
import {buildPortfolio,includeWpMenu} from '../src/features/menu-engineering/wpPortfolioModel.js';
for(const menu of ['AMZ: Deli Core','AMZ: Grill Core','AMZ: Salt & Char'])assert.equal(includeWpMenu(menu),true);
assert.equal(includeWpMenu('AMZ: Andes'),true);
for(const menu of ['AMZ: Pizzas & Flatbreads','Pizza','Flatbreads'])assert.equal(includeWpMenu(menu),true);
assert.equal(includeWpMenu('AMZ: Cafe Express Curated Sandwiches'),true);
const food={mrn:'001.23',name:'Roasted carrots',portion:'4 oz',massOz:4,cost:1,foodCost:1/2.8,category:'Vegetables',serviceReasons:[]};
const result=buildPortfolio([{menu:'A',items:[food]},{menu:'B',items:[{...food}]},{menu:'AMZ: Deli Core',items:[{...food,mrn:'deli'}]}]);
assert.equal(result.length,2);assert.deepEqual(result[0].menus,['A','B']);assert.equal(result[0].portfolioStatus,'Within 40%');
assert.equal(food.menus,undefined);
const conflict=buildPortfolio([{menu:'A',items:[food]},{menu:'B',items:[{...food,cost:2,foodCost:2/2.8}]}]);
assert.equal(conflict.length,1);assert.equal(conflict[0].foodCost,null);assert.equal(conflict[0].portfolioStatus,'Needs information');assert.equal(conflict[0].variants.length,2);
assert.equal(conflict[0].tier,'Needs information');assert.equal(conflict[0].cost,null);
assert.equal(buildPortfolio([{menu:'A',items:[{...food,foodCost:.4}]}])[0].portfolioStatus,'Within 40%');
assert.equal(buildPortfolio([{menu:'A',items:[{...food,foodCost:.401}]}])[0].portfolioStatus,'Above 40%');
assert.equal(buildPortfolio([{menu:'A',items:[{...food,serviceReasons:['Requires review']}]}])[0].portfolioStatus,'Service review');
assert.equal(buildPortfolio([{menu:'A',items:[{...food,mrn:''}]},{menu:'B',items:[{...food,mrn:''}]}]).length,2);
assert.equal(buildPortfolio([{menu:'A',items:[food]},{menu:'B',items:[{...food,portion:'8 oz',massOz:8,cost:2}]}]).length,1);
console.log('W&P portfolio identity, all-menu inclusion, conflicts and threshold checks passed');
