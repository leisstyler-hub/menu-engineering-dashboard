import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import COSTING from "../api/data/ingredientCosting91926.json" with { type: "json" };

const root = resolve(import.meta.dirname, "..");
const catalogPath = resolve(root, "src/features/commissary-ordering/breakfastCatalog.js");
const text = (value) => String(value ?? "").normalize("NFKC").trim().replace(/\s+/g, " ");
const mrn = (value) => text(value).replace(/^'/, "");
const slug = (value) => text(value).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const round = (value) => Number(Number(value).toFixed(6));

function prepComponent(component) {
  const name = text(component.ingredientName).replace(/^\s*\u2615\s*/, "");
  const componentMrn = mrn(component.ingredientMrn);
  const type = /^(amz|eur|eurna|ra|sub|thjv|exc):/i.test(name) ? "subrecipe" : "ingredient";
  return {
    id: `breakfast-prep|${type}|${componentMrn || slug(name)}|${component.unit}`,
    type,
    mrn: componentMrn,
    name,
    quantity: round(Number(component.quantity) / Number(component.recipeYield)),
    unit: component.unit,
  };
}

function exactComponents(recipeMrn) {
  const recipe = COSTING.recipes[mrn(recipeMrn)];
  if (!recipe) return null;
  const rows = [...(recipe.components || []), ...(recipe.unpricedComponents || [])];
  return rows.length ? rows.map(prepComponent) : null;
}

async function main() {
  const catalogUrl = process.argv.find((value) => value.startsWith("--catalog-url="))?.slice(14);
  if (!catalogUrl) throw new Error("Pass --catalog-url for the authoritative Supabase AMZ: Breakfast menu response.");
  const payload = await (await fetch(catalogUrl)).json();
  if (!String(payload?.source || "").startsWith("supabase-recipe-items") || payload?.selectedMenu !== "AMZ: Breakfast" || !Array.isArray(payload?.rows)) {
    throw new Error("The Breakfast catalog URL did not return the authoritative Supabase AMZ: Breakfast menu.");
  }
  const deduped = new Map();
  payload.rows
    .filter((row) => row.menu === "AMZ: Breakfast" && row.category === "entree" && /(sandwich|bagel|burrito)/i.test(text(row.item)))
    .forEach((row) => {
      const id = `breakfast|${mrn(row.mrn)}|${slug(row.portion)}`;
      if (!deduped.has(id)) deduped.set(id, { id, mrn: mrn(row.mrn), name: text(row.item), portion: text(row.portion), category: "entree" });
    });
  const items = [...deduped.values()].sort((a, b) => a.name.localeCompare(b.name) || a.mrn.localeCompare(b.mrn));
  if (!items.length) throw new Error("The filtered Breakfast sandwich, bagel and burrito roster is empty.");
  const itemPrepComponents = Object.fromEntries(items.map((item) => {
    const components = exactComponents(item.mrn);
    if (!components?.length) throw new Error(`Breakfast item ${item.name} / ${item.mrn} lacks an exact recipe projection.`);
    return [item.id, components];
  }));
  const program = {
    version: 1,
    menu: "AMZ: Breakfast",
    eligibleCafes: ["Brazil Coffee", "Roxanne Coffee", "Arizona Coffee"],
    quantityIncrement: 1,
    orderUnit: "item",
    includedTypes: ["sandwich", "bagel", "burrito"],
    exclusions: ["plate", "side", "cereal", "taco", "toast", "wrap", "chia", "extension"],
    items,
    itemPrepComponents,
    source: {
      catalog: "supabase.recipe_items",
      catalogRosterSha256: createHash("sha256").update(JSON.stringify(items)).digest("hex"),
      recipeProjection: COSTING.resource,
    },
  };
  const output = `// Generated by scripts/build-commissary-breakfast-catalog.mjs.\n// Contains exact Breakfast roster and prep quantities only; proprietary recipe methods are never projected.\n\nexport const BREAKFAST_ORDERING_PROGRAM = Object.freeze(${JSON.stringify(program, null, 2)});\n\nexport const BREAKFAST_ORDERING_ITEM_IDS = Object.freeze(BREAKFAST_ORDERING_PROGRAM.items.map(({ id }) => id));\nexport const BREAKFAST_ORDERING_PREP_ITEM_IDS = Object.freeze([...new Set(Object.values(BREAKFAST_ORDERING_PROGRAM.itemPrepComponents).flat().map(({ id }) => id))]);\n`;
  if (process.argv.includes("--check")) {
    if (readFileSync(catalogPath, "utf8").replace(/\r\n/g, "\n") !== output) throw new Error("Breakfast ordering catalog is stale.");
  } else writeFileSync(catalogPath, output);
  console.log(JSON.stringify({ items: items.length, prepIds: new Set(Object.values(itemPrepComponents).flat().map(({ id }) => id)).size, rosterSha256: program.source.catalogRosterSha256 }, null, 2));
}

main().catch((error) => { console.error(error.message); process.exit(1); });
