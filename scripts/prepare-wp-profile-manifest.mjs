import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {buildProfileManifest} from '../src/features/menu-engineering/wpProfileManifest.js';
const [snapshotPath,outputPath,incomingPath]=process.argv.slice(2);
if(!snapshotPath||!outputPath)throw new Error('Usage: node scripts/prepare-wp-profile-manifest.mjs <read-only-catalog.json> <new-output.json> [incoming-menu-rows.json]');
const snapshotBytes=readFileSync(snapshotPath),snapshot=JSON.parse(snapshotBytes);
if(!snapshot.source?.startsWith('supabase-recipe-items')||!Array.isArray(snapshot.rows))throw new Error('Trusted assembled read-view snapshot required; this is not a physical database backup');
const bytes=incomingPath?readFileSync(incomingPath):snapshotBytes;
const incoming=incomingPath?JSON.parse(bytes):snapshot;
const rows=Array.isArray(incoming)?incoming:incoming.rows;
const manifest=buildProfileManifest(rows,{source:incomingPath||snapshot.source,sourceSha256:createHash('sha256').update(bytes).digest('hex'),currentRows:snapshot.rows});
writeFileSync(outputPath,JSON.stringify(manifest,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({output:outputPath,state:manifest.state,...manifest.summary}));
