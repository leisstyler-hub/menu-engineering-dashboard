import assert from 'node:assert/strict';
import fs from 'node:fs';
import { panReadyMenu, assessPanReadyMenu, tierFor, CATEGORIES } from '../src/features/menu-engineering/panReadyModel.js';
const load = name => JSON.parse(fs.readFileSync(new URL(`../src/data/${name}WpAnalysis.json`, import.meta.url)));
const balti = load('balti'), andes = load('andes'), before = JSON.stringify(balti);
const result = panReadyMenu(balti, 11.2);
assert.ok(result.items.some(r => /Butter Chicken/.test(r.name)));
assert.ok(!result.items.some(r => /\bplate\b/i.test(r.name)));
assert.equal(result.items.filter(r => /Jeera Rice/.test(r.name)).length, 1);
const butter = result.items.find(r => /Butter Chicken/.test(r.name));
assert.equal(butter.massOz, null, 'Do not borrow a plate weight or component usage mass');
assert.ok(butter.components.some(e => /Marinade/.test(e.name)));
assert.ok(!result.items.some(r => /Marinade|Ginger Paste/.test(r.name)));
assert.ok(!panReadyMenu(andes, 11.2).items.some(r => /Puree/.test(r.name)));
assert.ok(panReadyMenu(andes, 11.2).items.some(r => /Stewed Tofu/.test(r.name)));
const sandwich={concept:'Test',recipes:[{id:'a',mrn:'001',name:'Chicken Burger',topLevel:true,components:[{childId:'b'}]},{id:'b',mrn:'002',name:'Roast Chicken',cost:1,massOz:4,components:[]}]};
assert.equal(panReadyMenu(sandwich,11.2).items.length,0);
assert.equal(JSON.stringify(balti),before);
assert.deepEqual([.3,.30001,.4,.40001,.5,.50001,.6,.60001,null].map(tierFor),['≤30%','>30–40%','>30–40%','>40–50%','>40–50%','>50–60%','>50–60%','>60%','Needs information']);
assert.ok(result.items.every(r=>CATEGORIES.includes(r.category)));
assert.equal(assessPanReadyMenu(result,11.2,true).total,result.items.length);
assert.equal(assessPanReadyMenu(panReadyMenu(sandwich,11.2),11.2,true).total,0);
const conflict={concept:'Test',recipes:[{id:'a',mrn:'001',name:'Roast Chicken',portion:'4 oz',massOz:4,cost:1,topLevel:true,components:[]},{id:'b',mrn:'001',name:'Roast Chicken',portion:'4 oz',massOz:4,cost:2,topLevel:true,components:[]}]};
const conflicted=panReadyMenu(conflict,11.2);
assert.ok(conflicted.items.every(r=>r.tier==='Needs information'));
assert.equal(assessPanReadyMenu(conflicted,11.2,true).status,'Conditional');
assert.equal(assessPanReadyMenu(conflicted,11.2,true).total,conflicted.items.length);
const {buildWeighPayPackage}=await import('../src/features/menu-engineering/weighPayExport.js');
const JSZip=(await import('jszip')).default;
const XLSX=await import('xlsx');
const blob=await buildWeighPayPackage([assessPanReadyMenu(result,11.2,true)],{pricePerLb:11.2,conceptAnalyses:{[result.menu]:result.items}});
const zip=await JSZip.loadAsync(await blob.arrayBuffer());
const workbook=XLSX.read(await zip.file('data-audit.xlsx').async('uint8array'));
const exported=XLSX.utils.sheet_to_json(workbook.Sheets['Servable Items']);
assert.equal(exported.length,result.items.length);
assert.ok(exported.every(r=>typeof r.MRN==='string'));
assert.ok(exported.every(r=>!r.Item.includes('Plate')));
const cards=await zip.file('flash-cards.html').async('string');
assert.ok(cards.includes('FC Needs information'));
assert.ok(!cards.includes('Chicken (Murgh Makhani) Plate'));
console.log('Pan-ready projection guards passed');
